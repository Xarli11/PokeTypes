#!/usr/bin/env node
// Regenerates src/lib/og/fonts/data.generated.ts and
// src/lib/og/pokeball.generated.ts from the binary sources in
// src/lib/og/fonts/*.ttf and public/pokeball.png.
//
// Why generated .ts modules instead of importing the binaries directly:
// Vite (as used by this project's version) only ships `?raw` (text) and
// `?url` (emitted-asset URL) import suffixes — no `?arraybuffer`. `?raw`
// would corrupt binary font/image data through UTF-8 decoding, and `?url`
// would mean fetching the asset at request time (one more thing that can
// fail per social-crawler hit, and a fetch that needs to resolve
// differently in Cloudflare Workers vs `astro dev`). A base64 string
// constant sidesteps both problems — it's just a JS string, bundles
// identically for Node and Workers, and needs no runtime I/O.
//
// src/lib/og/assets/pokeball-512.png is a 512x512 downscale of the app's
// public/pokeball.png (2052x2048) — cards only ever show it at <=320px, so
// embedding the full-resolution source would triple the generated file for
// no visible benefit. Regenerate it with:
//   sips -Z 512 public/pokeball.png --out src/lib/og/assets/pokeball-512.png
//
// Run this script manually after changing src/lib/og/fonts/*.ttf or
// src/lib/og/assets/pokeball-512.png:
//   node scripts/generate-og-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const FONTS = [
    ['syneBold', 'src/lib/og/fonts/Syne-Bold.ttf'],
    ['syneExtraBold', 'src/lib/og/fonts/Syne-ExtraBold.ttf'],
    ['outfitRegular', 'src/lib/og/fonts/Outfit-Regular.ttf'],
    ['outfitSemiBold', 'src/lib/og/fonts/Outfit-SemiBold.ttf'],
    ['outfitBold', 'src/lib/og/fonts/Outfit-Bold.ttf'],
    ['monoBold', 'src/lib/og/fonts/JetBrainsMono-Bold.ttf'],
];

function toBase64(relativePath) {
    return readFileSync(path.join(rootDir, relativePath)).toString('base64');
}

const fontsOut = [
    '// AUTO-GENERATED by scripts/generate-og-assets.mjs — do not edit by hand.',
    '// Base64 font data for the OG card renderer (see that script for why).',
    ...FONTS.map(([name, file]) => `export const ${name} = '${toBase64(file)}';`),
    '',
].join('\n');
writeFileSync(path.join(rootDir, 'src/lib/og/fonts/data.generated.ts'), fontsOut);

const pokeballOut = [
    '// AUTO-GENERATED by scripts/generate-og-assets.mjs — do not edit by hand.',
    `export const pokeballPngBase64 = '${toBase64('src/lib/og/assets/pokeball-512.png')}';`,
    '',
].join('\n');
writeFileSync(path.join(rootDir, 'src/lib/og/pokeball.generated.ts'), pokeballOut);

console.log('Regenerated src/lib/og/fonts/data.generated.ts and src/lib/og/pokeball.generated.ts');
